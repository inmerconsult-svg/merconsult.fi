const TABLES: Record<Lang, Dict> = { fi, en, sv, no, et };

type Ctx = {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: string, vars?: Record<string, string | number>) => string;
};

const I18nCtx = createContext<Ctx | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("fi");
  useEffect(() => {
    try {
      const s = localStorage.getItem("prego-lang") as Lang | null;
      if (s && LANGS.some((l) => l.id === s)) setLangState(s);
    } catch {
      /* ignore */
    }
  }, []);
  const setLang = (l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem("prego-lang", l);
    } catch {
      /* ignore */
    }
  };
  const t = useMemo(() => {
    const table = TABLES[lang];
    return (key: string, vars?: Record<string, string | number>) => {
      let s = table[key] ?? TABLES.en[key] ?? key;
      if (vars) {
        for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
      }
      return s;
    };
  }, [lang]);
  return <I18nCtx.Provider value={{ lang, setLang, t }}>{children}</I18nCtx.Provider>;
}

export function useI18n(): Ctx {
  const ctx = useContext(I18nCtx);
  if (!ctx) throw new Error("I18nProvider missing");
  return ctx;
}
